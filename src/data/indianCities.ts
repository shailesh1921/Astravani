export function searchIndianCities(query: string, limit: number = 8): string[] {
  if (!query || !query.trim()) {
    return POPULAR_CITIES_QUICK.slice(0, limit);
  }
  const cleanQ = query.toLowerCase().trim();
  const matched = ALL_INDIA_CITIES.filter((city) =>
    city.toLowerCase().includes(cleanQ)
  );
  return matched.slice(0, limit);
}
